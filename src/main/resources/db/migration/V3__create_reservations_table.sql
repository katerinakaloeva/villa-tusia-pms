CREATE TABLE reservations
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id           BIGINT         NOT NULL REFERENCES properties (id),

    guest_name            VARCHAR(120)   NOT NULL CHECK (BTRIM(guest_name) <> ''),
    guest_email           VARCHAR(254)   NOT NULL CHECK (BTRIM(guest_email) <> ''),
    guest_phone           VARCHAR(32)    NOT NULL CHECK (BTRIM(guest_phone) <> ''),

    check_in_date         DATE           NOT NULL,
    check_out_date        DATE           NOT NULL,
    guest_count           SMALLINT       NOT NULL CHECK (guest_count > 0),

    agreed_nightly_rate   NUMERIC(10, 2) NOT NULL CHECK (agreed_nightly_rate > 0),
    total_amount          NUMERIC(12, 2) NOT NULL CHECK (total_amount > 0),
    currency              VARCHAR(3)     NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),

    status                VARCHAR(20)    NOT NULL DEFAULT 'CONFIRMED'
        CHECK (status IN ('CONFIRMED', 'CANCELLED')),

    created_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT check_reservation_dates
        CHECK (check_out_date > check_in_date)
);