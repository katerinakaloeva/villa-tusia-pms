CREATE TABLE properties
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(120)   NOT NULL,
    location                 VARCHAR(255)   NOT NULL,
    description              TEXT,
    max_guests               SMALLINT       NOT NULL CHECK (max_guests > 0),
    base_nightly_rate        NUMERIC(10, 2) NOT NULL CHECK (base_nightly_rate > 0),
    currency                 VARCHAR(3)     NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    minimum_stay_nights      SMALLINT       NOT NULL CHECK (minimum_stay_nights > 0),
    check_in_time            TIME           NOT NULL,
    check_out_time           TIME           NOT NULL,
    time_zone                VARCHAR(50)    NOT NULL,
    cancellation_notice_days SMALLINT       NOT NULL CHECK (cancellation_notice_days >= 0),
    active                   BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
